import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import { transform } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const migrationPath = path.join(
  root,
  "supabase",
  "migrations",
  "202607290002_seed_portfolio_content_v1.sql"
);
const jsonDelimiter = "$portfolio_content_v1$";

async function read(relativePath) {
  return readFile(path.join(root, relativePath), "utf8");
}

async function loadNormalizedDefaults() {
  const caseSource = await read("case-sheet.jsx");
  const contentSource = await read("content.jsx");
  const transformedCaseSource = await transform(caseSource, {
    loader: "jsx",
    format: "iife",
    target: "es2020",
    jsxFactory: "React.createElement",
    jsxFragment: "React.Fragment",
    logLevel: "silent",
  });

  const storage = new Map();
  const context = {
    console: {
      log() {},
      warn() {},
      error() {},
    },
    CustomEvent: class CustomEvent {
      constructor(type, init) {
        this.type = type;
        this.detail = init?.detail;
      }
    },
    localStorage: {
      getItem: (key) => storage.get(key) ?? null,
      setItem: (key, value) => storage.set(key, value),
    },
    React: {
      Fragment: Symbol("Fragment"),
      createElement: () => null,
      useEffect: () => {},
      useState: (value) => [typeof value === "function" ? value() : value, () => {}],
    },
    window: {
      dispatchEvent: () => {},
      PortfolioIcons: { Close: () => null },
      PortfolioShared: {
        thumbs: {},
        GRAPHIC_PALETTES: [],
        WEBDEV_PALETTES: [],
      },
      PortfolioSupabase: null,
    },
  };

  vm.createContext(context);
  vm.runInContext(transformedCaseSource.code, context, { filename: "case-sheet.jsx" });
  vm.runInContext(contentSource, context, { filename: "content.jsx" });

  const api = context.window.PortfolioContent;
  assert.ok(api, "PortfolioContent did not initialize.");
  const content = api.normalize(api.defaults);

  assert.equal(content.schemaVersion, 1);
  assert.equal(Object.hasOwn(content, "schema_version"), false);
  assert.equal(
    content.services.graphic.length + content.services.webdev.length,
    20,
    "Expected all 20 service records."
  );
  assert.equal(
    content.projects.graphic.length + content.projects.webdev.length,
    20,
    "Expected all 20 category-project records."
  );
  assert.equal(
    content.works.graphic.length + content.works.webdev.length,
    12,
    "Expected all 12 selected-work records."
  );
  assert.deepEqual(
    Object.keys(content.cases).sort(),
    ["g1", "g2", "g3", "g4", "g5", "g6", "w1", "w2", "w3", "w4", "w5", "w6"]
  );

  return content;
}

function renderMigration(content) {
  const compactJson = JSON.stringify(content);
  const prettyJson = JSON.stringify(content, null, 2);
  const checksum = createHash("sha256").update(compactJson).digest("hex");

  if (prettyJson.includes(jsonDelimiter)) {
    throw new Error(`Seed JSON unexpectedly contains ${jsonDelimiter}.`);
  }

  return `-- Generated by scripts/generate-portfolio-seed.mjs.
-- Do not edit or regenerate this migration after it has been applied.
-- Canonical JSON SHA-256: ${checksum}
--
-- This seed is deliberately fail-safe: it initializes only an unequivocally
-- pristine singleton and never merges with, replaces, or publishes existing
-- draft data.

begin;

lock table public.portfolio_content in share row exclusive mode;
lock table public.portfolio_revisions in share row exclusive mode;
lock table public.portfolio_activity_log in share row exclusive mode;
lock table public.portfolio_publish_events in share row exclusive mode;

do $seed$
declare
  seed_content jsonb := ${jsonDelimiter}${prettyJson}${jsonDelimiter}::jsonb;
  seeded_at timestamptz := now();
  affected_rows integer := 0;
begin
  if not exists (
    select 1
    from public.portfolio_content
    where id = 1
  ) then
    raise exception 'Portfolio singleton is missing; apply the CMS schema migrations first.'
      using errcode = 'P0002';
  end if;

  if exists (
    select 1
    from public.portfolio_content
    where id = 1
      and (
        draft_json <> '{}'::jsonb
        or published_json <> '{}'::jsonb
        or draft_revision <> 0
        or published_revision <> 0
        or updated_by is not null
        or published_by is not null
        or published_at is not null
        or unpublished_at is not null
        or public_enabled is distinct from true
      )
  )
  or exists (select 1 from public.portfolio_revisions)
  or exists (select 1 from public.portfolio_activity_log) then
    raise notice 'Portfolio seed skipped because existing CMS state was detected.';
    return;
  end if;

  seed_content := public.validate_portfolio_content(seed_content);

  update public.portfolio_content
  set draft_json = seed_content,
      published_json = seed_content,
      draft_schema_version = 1,
      published_schema_version = 1,
      public_enabled = true,
      draft_revision = 0,
      published_revision = 0,
      updated_by = null,
      published_by = null,
      updated_at = seeded_at,
      published_at = seeded_at,
      unpublished_at = null
  where id = 1
    and draft_json = '{}'::jsonb
    and published_json = '{}'::jsonb
    and draft_revision = 0
    and published_revision = 0
    and updated_by is null
    and published_by is null
    and published_at is null
    and unpublished_at is null
    and public_enabled is true;

  get diagnostics affected_rows = row_count;
  if affected_rows <> 1 then
    raise exception 'Portfolio state changed while the seed was being applied.'
      using errcode = '40001';
  end if;

  insert into public.portfolio_revisions (
    revision, kind, content_json, created_by, created_at
  )
  values
    (0, 'draft', seed_content, null, seeded_at),
    (0, 'published', seed_content, null, seeded_at);

  insert into public.portfolio_activity_log (
    actor_id, action, resource_type, resource_id, metadata, created_at
  )
  values (
    null,
    'portfolio.seeded',
    'portfolio',
    'main',
    jsonb_build_object(
      'schemaVersion', 1,
      'sha256', '${checksum}'
    ),
    seeded_at
  );

  insert into public.portfolio_publish_events (
    published_revision, created_at
  )
  values (0, seeded_at);
end
$seed$;

commit;
`;
}

function readGuardedSeed(migration) {
  const checksumMatch = migration.match(/Canonical JSON SHA-256:\s*([a-f0-9]{64})/i);
  const jsonMatch = migration.match(
    /\$portfolio_content_v1\$([\s\S]*?)\$portfolio_content_v1\$::jsonb/
  );

  assert.ok(checksumMatch, "The guarded seed checksum is missing.");
  assert.ok(jsonMatch, "The guarded seed JSON is missing.");

  const content = JSON.parse(jsonMatch[1]);
  const checksum = createHash("sha256")
    .update(JSON.stringify(content))
    .digest("hex");
  assert.equal(
    checksum,
    checksumMatch[1].toLowerCase(),
    "The immutable seed JSON no longer matches its recorded checksum."
  );
  return { content, checksum };
}

function assertCanonicalInventory(content, label) {
  assert.equal(content.schemaVersion, 1, `${label} must use schema version 1.`);
  assert.equal(
    Object.hasOwn(content, "schema_version"),
    false,
    `${label} must not persist the legacy schema_version alias.`
  );
  assert.equal(
    content.services.graphic.length + content.services.webdev.length,
    20,
    `${label} must contain all 20 service records.`
  );
  assert.equal(
    content.projects.graphic.length + content.projects.webdev.length,
    20,
    `${label} must contain all 20 category-project records.`
  );
  assert.equal(
    content.works.graphic.length + content.works.webdev.length,
    12,
    `${label} must contain all 12 selected-work records.`
  );
  assert.deepEqual(
    Object.keys(content.cases).sort(),
    ["g1", "g2", "g3", "g4", "g5", "g6", "w1", "w2", "w3", "w4", "w5", "w6"],
    `${label} must contain the canonical case inventory.`
  );
}

const mode = process.argv[2] || "--check";
if (!["--write", "--check"].includes(mode)) {
  throw new Error("Usage: node scripts/generate-portfolio-seed.mjs --write|--check");
}

if (mode === "--write") {
  const content = await loadNormalizedDefaults();
  const migration = renderMigration(content);
  try {
    await readFile(migrationPath, "utf8");
    throw new Error(
      "The seed migration already exists. Applied migrations are immutable; create a new migration for later seed changes."
    );
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  await writeFile(migrationPath, migration, "utf8");
  console.log(`Created ${path.relative(root, migrationPath)}.`);
} else {
  const content = await loadNormalizedDefaults();
  const existing = await readFile(migrationPath, "utf8");
  const guardedSeed = readGuardedSeed(existing);
  assertCanonicalInventory(guardedSeed.content, "The immutable guarded seed");
  assertCanonicalInventory(content, "The current normalized defaults");
  console.log(
    `Portfolio seed integrity verified (${guardedSeed.checksum}); current defaults normalize to the canonical inventory.`
  );
}
